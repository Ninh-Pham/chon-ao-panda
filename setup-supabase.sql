create or replace function public.admin_verify(p_admin_token text)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not exists (
    select 1 from public.app_admin_settings
    where id = 1 and secret_hash = crypt(p_admin_token, secret_hash)
  ) then
    raise exception 'Mã quản trị không đúng.' using errcode = '42501';
  end if;
  return true;
end;
$$;

create or replace function public.admin_create_jersey(
  p_admin_token text,
  p_name text,
  p_image_url text,
  p_code text default null,
  p_category text default 'Thi đấu',
  p_colorway text default null,
  p_description text default null
)
returns public.jerseys
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  created_jersey public.jerseys;
begin
  if not exists (
    select 1 from public.app_admin_settings
    where id = 1 and secret_hash = crypt(p_admin_token, secret_hash)
  ) then
    raise exception 'Mã quản trị không đúng.' using errcode = '42501';
  end if;

  insert into public.jerseys (name, image_url, code, category, colorway, description)
  values (
    trim(p_name),
    p_image_url,
    nullif(trim(p_code), ''),
    coalesce(nullif(trim(p_category), ''), 'Thi đấu'),
    nullif(trim(p_colorway), ''),
    nullif(trim(p_description), '')
  )
  returning * into created_jersey;
  return created_jersey;
end;
$$;

create or replace function public.admin_set_jersey_active(
  p_admin_token text,
  p_jersey_id bigint,
  p_active boolean
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not exists (
    select 1 from public.app_admin_settings
    where id = 1 and secret_hash = crypt(p_admin_token, secret_hash)
  ) then
    raise exception 'Mã quản trị không đúng.' using errcode = '42501';
  end if;

  update public.jerseys set is_active = p_active where id = p_jersey_id;
  return found;
end;
$$;

create or replace function public.admin_set_registration_status(
  p_admin_token text,
  p_registration_id uuid,
  p_status text
)
returns boolean
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if not exists (
    select 1 from public.app_admin_settings
    where id = 1 and secret_hash = crypt(p_admin_token, secret_hash)
  ) then
    raise exception 'Mã quản trị không đúng.' using errcode = '42501';
  end if;
  if p_status not in ('pending', 'confirmed', 'production', 'ready') then
    raise exception 'Trạng thái không hợp lệ.' using errcode = '22023';
  end if;

  update public.registrations set status = p_status where id = p_registration_id;
  return found;
end;
$$;

