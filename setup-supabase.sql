create extension if not exists pgcrypto with schema extensions;

create table if not exists public.jerseys (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 60),
  image_url text not null,
  code text,
  category text not null default 'Thi đấu',
  colorway text,
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- Nâng cấp an toàn nếu dự án đang dùng bản cũ.
alter table public.jerseys add column if not exists code text;
alter table public.jerseys add column if not exists category text not null default 'Thi đấu';
alter table public.jerseys add column if not exists colorway text;
alter table public.jerseys add column if not exists description text;
alter table public.jerseys add column if not exists is_active boolean not null default true;

create table if not exists public.registrations (
  id uuid primary key default gen_random_uuid(),
  full_name text not null check (char_length(full_name) between 2 and 80),
  print_name text check (print_name is null or char_length(print_name) <= 20),
  shirt_number integer not null check (shirt_number between 0 and 99),
  size text not null check (size in ('XS', 'S', 'M', 'L', 'XL', '2XL', '3XL')),
  note text check (note is null or char_length(note) <= 300),
  jersey_id bigint not null references public.jerseys(id) on delete restrict,
  status text not null default 'pending' check (status in ('pending', 'confirmed', 'production', 'ready')),
  created_at timestamptz not null default now()
);

alter table public.registrations add column if not exists status text not null default 'pending';

create index if not exists jerseys_active_created_idx on public.jerseys(is_active, created_at desc);
create index if not exists registrations_created_at_idx on public.registrations(created_at desc);
create index if not exists registrations_jersey_id_idx on public.registrations(jersey_id);

